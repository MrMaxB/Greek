ACUTE = "́"
# одиночные буквы
ONE = {"α":"а","β":"в","γ":"г","δ":"ð","ε":"э","ζ":"з","η":"и","θ":"θ","ι":"и",
       "κ":"к","λ":"л","μ":"м","ν":"н","ξ":"кс","ο":"о","π":"п","ρ":"р","σ":"с","ς":"с",
       "τ":"т","υ":"и","φ":"ф","χ":"х","ψ":"пс","ω":"о"}
DI = {"ου":"у","αι":"э","ει":"и","οι":"и","υι":"и","αυ":"ав","ευ":"эв",
      "μπ":"б","ντ":"д","γκ":"г","γγ":"нг","τσ":"ц","τζ":"дз"}

def strip_acc(ch):
    d = unicodedata.normalize("NFD", ch)
    base = "".join(c for c in d if unicodedata.category(c) != "Mn")
    return base, (ACUTE in d or "̈́" in d)

def translit(word):
    s = word.lower()
    out = []
    i = 0
    while i < len(s):
        # пробуем диграф (по «голым» буквам)
        if i + 1 < len(s):
            b0, a0 = strip_acc(s[i]); b1, a1 = strip_acc(s[i+1])
            di = b0 + b1
            if di in DI:
                cy = DI[di]
                if a0 or a1:
                    # ставим ударение на первую гласную кириллицы
                    cy = cy[0] + ACUTE + cy[1:]
                out.append(cy); i += 2; continue
        b, a = strip_acc(s[i])
        if b in ONE:
            cy = ONE[b]
            if a:
                cy = cy[0] + ACUTE + cy[1:]
            out.append(cy)
        elif b == " ":
            out.append(" ")
        i += 1
    return "".join(out)

