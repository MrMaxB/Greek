def nrm(s):
    s = unicodedata.normalize("NFD", s.lower())
    s = "".join(c for c in s if unicodedata.category(c) != "Mn")
    return s.replace("ς", "σ").strip()

def existing_words():
    src = open(os.path.join(ROOT, "js", "data.js"), encoding="utf-8").read()
    return set(nrm(g) for g in re.findall(r'gr:\s*"([^"]+)"', src))

def official_set():
    # авторитетный «недостающий» список этой сессии (греческий из глоссария)
    p = "/tmp/miss.txt"
    if os.path.exists(p):
        return set(nrm(l.split("\t", 1)[0]) for l in open(p, encoding="utf-8") if l.strip())
    p2 = os.path.join(ROOT, "docs", "data", "official_a1_headwords.txt")
    return set(l.strip() for l in open(p2, encoding="utf-8") if l.strip())

def gen_js(skip_existing=True):
    have = existing_words() if skip_existing else set()
    off = official_set()
    blocks = []
    skipped = []
    for (did, icon, title), words in BATCH.items():
        rows = []
        for gr, ru in words:
            k = nrm(gr)
            if k in have: skipped.append((gr, "уже есть")); continue
            if k not in off: skipped.append((gr, "не в списке недостающих")); continue
            rows.append(f'      {{ gr: "{gr}", tr: "{translit(gr)}", ru: "{ru.replace(chr(34), chr(39))}" }},')
        if rows:
            blocks.append(f'  {{\n    id: "{did}",\n    icon: "{icon}",\n    title: "{title}",\n    words: [\n' + "\n".join(rows) + "\n    ],\n  },")
    for gr, why in skipped:
        print("  skip:", gr, "—", why)
    return "\n".join(blocks)

if "--apply" in sys.argv:
    p = os.path.join(ROOT, "js", "data.js")
    src = open(p, encoding="utf-8").read()
    marker = "\n];\n\n/* Теория грамматики"
    assert marker in src, "маркер конца DECKS не найден"
