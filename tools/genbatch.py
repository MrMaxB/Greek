def gen_js():
    blocks = []
    for (did, icon, title), words in BATCH.items():
        rows = []
        for gr, ru in words:
            tr = translit(gr)
            ru = ru.replace('"', "'")
            rows.append(f'      {{ gr: "{gr}", tr: "{tr}", ru: "{ru}" }},')
        block = f'  {{\n    id: "{did}",\n    icon: "{icon}",\n    title: "{title}",\n    words: [\n' + "\n".join(rows) + "\n    ],\n  },"
        blocks.append(block)
    return "\n".join(blocks)

