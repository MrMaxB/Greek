const DECKS = [...DECKS_CORE, ...DECKS_EXTRA];

/* Теория грамматики, склонения и спряжения — в js/grammar.js */

/* ---------- ИНИЦИАЛИЗАЦИЯ id ---------- */
// Стабильные id нужны для хранения прогресса SRS (id = "<deck>_<индекс>").
// ВНИМАНИЕ: id зависит от ПОРЯДКА слов в колоде. НЕ переупорядочивай и НЕ
// удаляй существующие слова в data-decks-*.js — это сдвинет id и «потеряет»
// прогресс пользователя по сдвинутым словам. Новые слова добавляй В КОНЕЦ колоды.
DECKS.forEach((deck) => {
  deck.words.forEach((w, i) => {
    w.id = deck.id + "_" + i;
    w.deck = deck.id;
    w.deckTitle = deck.title;
  });
});

// Плоский список всех слов
const ALL_WORDS = DECKS.flatMap((d) => d.words);
